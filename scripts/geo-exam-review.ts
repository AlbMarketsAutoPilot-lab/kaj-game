// Writes the review page of the citizenship-test geography facts (step 2.3): node scripts/geo-exam-review.ts
// The owner marks wrong facts on this page; corrections go back into src/facts/geo-exam.ts.
import { writeFileSync } from 'node:fs';
import { GEO_EXAM_50 } from '../src/facts/geo-exam.ts';
import { map50 } from '../src/maps/map50.ts';

const name = new Map(map50.areas.map((a) => [a.id, a.name]));
const missing = map50.areas.filter((a) => !GEO_EXAM_50[a.id]?.length).map((a) => a.id);
if (missing.length) throw new Error(`no geography facts for: ${missing.join(', ')}`);
const count = Object.values(GEO_EXAM_50).reduce((sum, facts) => sum + facts.length, 0);
const cell = (s: string) => s.replaceAll('|', '\\|');
const lines = [
  '# Geography facts for the citizenship test (generated by `node scripts/geo-exam-review.ts`, do not edit by hand)',
  '',
  `${Object.keys(GEO_EXAM_50).length} areas of the 50-turn map · ${count} facts. Source: \`src/facts/geo-exam.ts\`.`,
  'Asked only in the citizenship test, not in the airline quiz (step 2.3). The 30-turn map takes at most 3 per area.',
  '',
  'To report a problem, give the area and the number (for example "Spain 2: wrong sea").',
  'The right answer is in **bold**.',
];
for (const [id, facts] of Object.entries(GEO_EXAM_50)) {
  lines.push('', `## ${name.get(id) ?? id}`, '', '| # | Fact | Question | Answers |', '|---|---|---|---|');
  facts.forEach((fact, k) => lines.push(`| ${k + 1} | ${cell(fact.text)} | ${cell(fact.question)} | **${cell(fact.right)}** / ${cell(fact.wrong)} |`));
}
writeFileSync('docs/facts/geo-exam.md', lines.join('\n') + '\n');
console.log(`docs/facts/geo-exam.md: ${count} facts`);
