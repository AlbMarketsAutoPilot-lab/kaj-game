// Writes the review pages of the 100-turn map's facts (step 2.12 part J4): node scripts/facts100-review.ts
// - docs/facts/new100-1.md (Europe and Asia) and docs/facts/new100-2.md (Africa and the Americas): the new facts and the
//   new test-only geography facts, with their type, for the owner to check; corrections go back into src/facts/new100.ts.
// - docs/facts/sort100.md: where each fact of a split 50-turn area went (src/facts/sort100.ts).
import { writeFileSync } from 'node:fs';
import { factId } from '../src/engine/quiz.ts';
import { FACTS_100_NEW, GEO_EXAM_100_NEW } from '../src/facts/new100.ts';
import { EXAM_SORT_100, SORT_100 } from '../src/facts/sort100.ts';
import { FACT_TYPES } from '../src/facts/tags.ts';
import type { Fact } from '../src/facts/types.ts';
import { map50 } from '../src/maps/map50.ts';
import { map100 } from '../src/maps/map100.ts';

const cell = (s: string) => s.replaceAll('|', '\\|');
const name100 = new Map(map100.areas.map((a) => [a.id, a.name]));
const name50 = new Map(map50.areas.map((a) => [a.id, a.name]));
const typeOf = (fact: Fact) => {
  const t = FACT_TYPES[factId(fact)];
  if (!t) throw new Error(`no type in src/facts/tags.ts: ${fact.question}`);
  return t;
};
const row = (k: number, fact: Fact) =>
  `| ${k} | ${cell(fact.text)} | ${cell(fact.question)} | **${cell(fact.right)}** / ${cell(fact.wrong)} | ${typeOf(fact)} |`;

const PAGES = [
  { file: 'docs/facts/new100-1.md', title: 'Europe and Asia', continents: ['Europe', 'Asia'] },
  { file: 'docs/facts/new100-2.md', title: 'Africa and the Americas', continents: ['Africa', 'North America', 'South America'] },
];
for (const page of PAGES) {
  const areas = map100.areas.filter((a) => page.continents.includes(a.continent) && (FACTS_100_NEW[a.id] || GEO_EXAM_100_NEW[a.id]));
  const facts = areas.flatMap((a) => FACTS_100_NEW[a.id] ?? []);
  const exam = areas.flatMap((a) => GEO_EXAM_100_NEW[a.id] ?? []);
  const geo = facts.filter((f) => typeOf(f) === 'geography').length;
  const lines = [
    `# New facts for the 100-turn map: ${page.title} (generated by \`node scripts/facts100-review.ts\`, do not edit by hand)`,
    '',
    `${areas.length} areas · ${facts.length} new facts (${geo} geography, ${facts.length ? Math.round((100 * geo) / facts.length) : 0}%) · ${exam.length} new test-only geography facts.`,
    'Source: `src/facts/new100.ts`; types in `src/facts/tags.ts`. Each area also keeps the facts of its 50-turn area that are',
    'about its countries (`docs/facts/sort100.md`). Test-only facts are asked only in the citizenship and visa test.',
    '',
    'To report a problem, give the area and the number (for example "Austria 3: wrong dance" or "Austria T1: wrong lake").',
    'The right answer is in **bold**.',
  ];
  if (!areas.length) lines.push('', 'Not written yet (step 2.12 part J4, session 2).');
  for (const a of areas) {
    lines.push('', `## ${a.name}`, '', '| # | Fact | Question | Answers | Type |', '|---|---|---|---|---|');
    (FACTS_100_NEW[a.id] ?? []).forEach((fact, k) => lines.push(row(k + 1, fact)));
    (GEO_EXAM_100_NEW[a.id] ?? []).forEach((fact, k) => lines.push(row(k + 1, fact).replace(/^\| \d+ /, `| T${k + 1} `)));
  }
  writeFileSync(page.file, lines.join('\n') + '\n');
  console.log(`${page.file}: ${areas.length} areas, ${facts.length} facts (${geo} geography), ${exam.length} test facts`);
}

// Where the 50-turn facts went.
const to = (s: string) => (s === '-' ? '— (repeats another fact there)' : s.split('+').map((id) => name100.get(id) ?? id).join(' + '));
const lines = [
  '# The 50-turn facts sorted by country for the 100-turn map (generated by `node scripts/facts100-review.ts`, do not edit by hand)',
  '',
  `${Object.keys(SORT_100).length} areas of the 50-turn map are split on the 100-turn map. Each of their facts goes to the`,
  'area(s) of the country it is about (`src/facts/sort100.ts`). T1 and T2 are the test-only geography facts.',
  'The 55 areas that are the same place on both maps keep all their facts and are not listed.',
];
for (const [p, sort] of Object.entries(SORT_100)) {
  lines.push('', `## ${name50.get(p) ?? p}`, '', '| # | Fact | Goes to |', '|---|---|---|');
  map50.facts![p].forEach((fact, k) => lines.push(`| ${k + 1} | ${cell(fact.text)} | ${to(sort[k])} |`));
  map50.examFacts![p].forEach((fact, k) => lines.push(`| T${k + 1} | ${cell(fact.text)} | ${to(EXAM_SORT_100[p][k])} |`));
}
writeFileSync('docs/facts/sort100.md', lines.join('\n') + '\n');
console.log(`docs/facts/sort100.md: ${Object.keys(SORT_100).length} areas`);
