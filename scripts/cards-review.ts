// Writes the event-card review page: node scripts/cards-review.ts
// The owner marks cards to change on this page; corrections go back into src/cards/cards.ts.
import { writeFileSync } from 'node:fs';
import { CARDS } from '../src/cards/cards.ts';
import { EVENT_MIX } from '../src/engine/constants.ts';
import { newsCard } from '../src/engine/engine.ts';
import type { EventCard } from '../src/engine/types.ts';
import { map30 } from '../src/maps/map30.ts';

const effect = (points: number, loseTurn?: true) => (loseTurn ? 'lose a turn' : points > 0 ? `+${points}` : `${points}`);
const country = CARDS.filter((c) => c.deck === 'country');
const backpacker = CARDS.filter((c) => c.deck === 'backpacker');
const count = (cards: EventCard[], f: (c: EventCard) => boolean) => cards.filter(f).length;
// Examples: a normal area (taking turns) and a part of a big country.
const EXAMPLES = ['chile', 'japan', 'egypt', 'iberia', 'india', 'mexico', 'turkey-caucasus', 'northern-andes', 'scandinavia', 'west-africa', 'korea', 'italy', 'uk-ireland', 'new-zealand', 'greece'];
const BIG = ['usa-west', 'russia-far-east', 'brazil-north', 'china-west', 'canada-east', 'australia-east'];
const area = (id: string) => map30.areas.find((a) => a.id === id)!;
const cell = (s: string) => s.replaceAll('|', '\\|');

const mixRows: string[] = [];
for (const turns of ['30', '50'] as const) {
  for (const p of ['backpacker', 'business', 'luxury', 'nomad'] as const) {
    const m = (players: '2' | '4') => {
      const x = EVENT_MIX[turns][players][p];
      return x ? `good ${x.good}×, bad ${x.bad}×` : 'normal deck';
    };
    mixRows.push(`| ${turns} turns | ${p[0].toUpperCase() + p.slice(1)} | ${m('2')} | ${m('4')} |`);
  }
}

const lines = [
  '# Event cards (generated by `node scripts/cards-review.ts`, do not edit by hand)',
  '',
  `${country.length} news cards, drawn everywhere. Source: \`src/cards/cards.ts\`. ` +
    `+1: ${count(country, (c) => c.points === 1)} · −1: ${count(country, (c) => c.points === -1)} · +2: ${count(country, (c) => c.points === 2)} · ` +
    `−2: ${count(country, (c) => c.points === -2)} · lose a turn: ${count(country, (c) => c.loseTurn === true)} · +5: ${count(country, (c) => c.points === 5)} · ` +
    `−5: ${count(country, (c) => c.points === -5)}.`,
  '',
  "When: at the start of each player's 3rd, 6th, 9th … turn that begins in an area (every 5th in the 50-turn game;",
  "trip turns don't count; none in the last round). No cards on trips since task 12 (challenges instead).",
  'Points never go below 0.',
  '',
  '**Step 2.8 (owner): news about the country where the player stands.** The game fills in {country}, {capital} and',
  '{currency} from `data/countries.json` (table `src/cards/countries.ts`, made by `node scripts/card-countries.ts`).',
  'In an area with several countries they take turns (very small ones left out). In a part of a big country (USA, Canada,',
  'Russia, China, Brazil, Australia) a card that names the capital uses its big-country text instead. The 12 old',
  'own-area cards (a1–a12) are general cards now (c34–c45, same points).',
  '',
  '**Card mix "N1" by map, profile and number of players** (step 2.8; `EVENT_MIX` in `src/engine/constants.ts`; 3 players use the',
  '4-player mix): a good card counts "good" times, a bad one (points below 0, or a lost turn) "bad" times.',
  '',
  '| Map | Profile | 2 players | 3 or 4 players |',
  '|---|---|---|---|',
  ...mixRows,
  '',
  'To report a problem, give the id (for example "c7: …").',
  '',
  '## News cards (everywhere)',
  '',
  '| Id | Effect | Headline | Card | Big-country text | Example |',
  '|---|---|---|---|---|---|',
];
let i = 0, j = 0;
for (const c of country) {
  const a = area(EXAMPLES[i++ % EXAMPLES.length]);
  let example = `News from ${a.name}: “${newsCard(c, a, 0).text}”`;
  if (c.big) {
    const b = area(BIG[j++ % BIG.length]);
    example += `<br>News from ${b.name}: “${newsCard(c, b, 0).text}”`;
  }
  lines.push(`| ${c.id} | ${effect(c.points, c.loseTurn)} | ${cell(c.title)} | ${cell(c.text)} | ${c.big ? cell(c.big) : 'same'} | ${cell(example)} |`);
}
lines.push('', '## Backpacker cards (kept, not drawn since step 2.6)', '', '| Id | Headline | Card | Effect |', '|---|---|---|---|');
for (const c of backpacker) lines.push(`| ${c.id} | ${c.title} | ${c.text} | ${effect(c.points, c.loseTurn)} |`);
writeFileSync('docs/cards.md', lines.join('\n') + '\n');
console.log(`docs/cards.md: ${CARDS.length} cards`);
